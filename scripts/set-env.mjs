import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

// Simple .env parser to avoid heavy external dependencies
function loadEnvFile(filePath) {
  const env = {};
  if (!fs.existsSync(filePath)) return env;
  const content = fs.readFileSync(filePath, 'utf8');
  for (const rawLine of content.split('\n')) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const eqIdx = line.indexOf('=');
    if (eqIdx !== -1) {
      const key = line.slice(0, eqIdx).trim();
      let val = line.slice(eqIdx + 1).trim();
      // Remove surrounding quotes if present
      if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
        val = val.slice(1, -1);
      }
      env[key] = val;
    }
  }
  return env;
}

const envFile = loadEnvFile(path.join(rootDir, '.env'));

function getEnv(key, fallback = '') {
  return process.env[key] || envFile[key] || fallback;
}

const firebaseConfig = {
  apiKey: getEnv('FIREBASE_API_KEY', ''),
  authDomain: getEnv('FIREBASE_AUTH_DOMAIN', ''),
  projectId: getEnv('FIREBASE_PROJECT_ID', ''),
  storageBucket: getEnv('FIREBASE_STORAGE_BUCKET', ''),
  messagingSenderId: getEnv('FIREBASE_MESSAGING_SENDER_ID', ''),
  appId: getEnv('FIREBASE_APP_ID', ''),
  measurementId: getEnv('FIREBASE_MEASUREMENT_ID', '')
};

const googleClientId = getEnv('GOOGLE_CLIENT_ID', '');
const authorizedEmail = getEnv('AUTHORIZED_EMAIL', '');
const driveAppFolderName = getEnv('DRIVE_APP_FOLDER_NAME', 'REMINDER_APP');
const driveScopes = getEnv(
  'DRIVE_SCOPES',
  'https://www.googleapis.com/auth/drive.file https://www.googleapis.com/auth/userinfo.profile https://www.googleapis.com/auth/userinfo.email'
);

function generateEnvContent(isProd) {
  return `// Auto-generated by scripts/set-env.mjs from .env and environment variables
// DO NOT commit sensitive private keys to version control.
export const environment = {
  production: ${isProd},
  appVersion: '1.0.0',
  googleClientId: ${JSON.stringify(googleClientId)},
  authorizedEmail: ${JSON.stringify(authorizedEmail)},
  driveAppFolderName: ${JSON.stringify(driveAppFolderName)},
  driveScopes: ${JSON.stringify(driveScopes)},
  firebaseConfig: ${JSON.stringify(firebaseConfig, null, 4)}
};
`;
}

const envDir = path.join(rootDir, 'src', 'environments');
if (!fs.existsSync(envDir)) {
  fs.mkdirSync(envDir, { recursive: true });
}

fs.writeFileSync(path.join(envDir, 'environment.ts'), generateEnvContent(false));
fs.writeFileSync(path.join(envDir, 'environment.prod.ts'), generateEnvContent(true));

console.log('✓ Successfully generated environment files from .env configuration');
